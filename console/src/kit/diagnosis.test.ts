import { afterEach, describe, expect, it, vi } from "vitest";
import { readFileSync } from "node:fs";
import { setToken } from "@/lib/token";
import { appDiagnosisResource, projectFindingsResource, FINDINGS_PAGE_SIZE } from "./diagnosis";

// 诊断读面资源锚（B2a W4）：两资源走 rest 工厂（record = DiagnoseApp、
// collection = ListProjectFindings 服务端 keyset）——端点/信封展平/游标组参
// 在此钉死；fetch 面 stub 在 global（rest 工厂经 authFetch 走裸 fetch）。

afterEach(() => {
  vi.unstubAllGlobals();
  setToken("");
});

function jsonResponse(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json" } });
}

const FINDING = {
  finding_id: "F_WORKLOAD_CRASH_LOOP",
  severity: "warning",
  fault_class: "app",
  workload_id: "w1",
  process: "web",
  message: "The workload keeps terminating and restarting in the near window.",
  evidence: { state: "failed", exit_code: 1, restart_count: 4, recent_event: "workload.terminated" },
  fix: { verb: "restart", params: { process: "web" }, console_path: "/p/P1/apps/A1" },
};

describe("读面锚：app-diagnosis record（DiagnoseApp）", () => {
  it("打 GET /v1/apps/{id}/diagnosis 并展平 findings/unreadable_faces", async () => {
    const fetchMock = vi.fn(async () => jsonResponse({ findings: [FINDING], unreadable_faces: ["components"] }));
    vi.stubGlobal("fetch", fetchMock);

    const record = await appDiagnosisResource.record!("current", { projectId: "P1", appId: "A1" }, undefined);

    expect(record).toEqual({ findings: [FINDING], unreadableFaces: ["components"] });
    const [url, init] = fetchMock.mock.calls[0] as unknown as [string, RequestInit];
    expect(String(url)).toBe("/v1/apps/A1/diagnosis");
    expect(init?.method).toBeUndefined(); // 纯读：GET（无 method 即 GET）
  });
});

describe("读面锚：project-findings collection（ListProjectFindings 服务端 keyset）", () => {
  it("首页打 limit=FINDINGS_PAGE_SIZE 无游标", async () => {
    const fetchMock = vi.fn(async () => jsonResponse({ apps: [{ app_id: "A1", app_seq: "1", app_name: "api", findings: [FINDING] }] }));
    vi.stubGlobal("fetch", fetchMock);

    const segment = await projectFindingsResource.collection!({ window: { size: FINDINGS_PAGE_SIZE } }, { projectId: "P1" }, undefined);

    expect(segment.rows).toHaveLength(1);
    expect(segment.rows[0]).toMatchObject({ app_id: "A1" });
    const [url] = fetchMock.mock.calls[0] as unknown as [string];
    expect(String(url)).toBe(`/v1/projects/P1/findings?limit=${FINDINGS_PAGE_SIZE}`);
  });

  it("游标页带 after_app_seq（window.cursor → 服务端游标）", async () => {
    const fetchMock = vi.fn(async () => jsonResponse({ apps: [] }));
    vi.stubGlobal("fetch", fetchMock);

    await projectFindingsResource.collection!(
      { window: { size: FINDINGS_PAGE_SIZE, cursor: "12" } },
      { projectId: "P1" },
      undefined,
    );

    const [url] = fetchMock.mock.calls[0] as unknown as [string];
    expect(String(url)).toBe(`/v1/projects/P1/findings?after_app_seq=12&limit=${FINDINGS_PAGE_SIZE}`);
  });

  it("整窗占满 → nextCursor = 末条 app_seq 回显；短页 → 无 nextCursor（ListApps 短页惯例）", async () => {
    // 整窗：50 行（先行筛命中的 App 才占响应——行数 = 页大小即可能还有
    // 更多 App，hasMore 只能由整窗推导）；游标页（第二次调用）短页到底。
    const full = Array.from({ length: FINDINGS_PAGE_SIZE }, (_, i) => ({ app_id: `A${i}`, app_seq: String(i + 1) }));
    const pages = [{ apps: full }, { apps: full.slice(0, 3) }];
    const fetchMock = vi.fn(async () => jsonResponse(pages.shift() ?? { apps: [] }));
    vi.stubGlobal("fetch", fetchMock);

    const fullSegment = await projectFindingsResource.collection!({ window: { size: FINDINGS_PAGE_SIZE } }, { projectId: "P1" }, undefined);
    expect(fullSegment.nextCursor).toBe(String(FINDINGS_PAGE_SIZE));

    const shortSegment = await projectFindingsResource.collection!(
      { window: { size: FINDINGS_PAGE_SIZE, cursor: "50" } },
      { projectId: "P1" },
      undefined,
    );
    expect(shortSegment.nextCursor).toBeUndefined();
  });
});

// 生成层纪律（W4 交付 1）：diagnosis 上下文经 gen.mjs CONTEXTS 镜像生成，
// 产物是 openapi-typescript 纯类型——零手写 fetch（读管线单源 authFetch）。
describe("生成层零手写 fetch（diagnosis 上下文）", () => {
  it("src/api/diagnosis.ts 是 openapi-typescript 纯类型产物（零 fetch 调用）", () => {
    const src = readFileSync("src/api/diagnosis.ts", "utf8");
    expect(src).toContain("auto-generated by openapi-typescript");
    expect(src).not.toMatch(/\bfetch\s*\(/);
    // 消费的类型面真实在册（两响应 + 条目三件）。
    expect(src).toContain("v1DiagnoseAppResponse");
    expect(src).toContain("v1ListProjectFindingsResponse");
    expect(src).toContain("v1FindingEvidence");
    expect(src).toContain("v1FindingFix");
  });

  it("gen.mjs CONTEXTS 含 diagnosis 且镜像指向 runtime/v1/diagnosis.swagger.json", () => {
    const gen = readFileSync("src/api/gen.mjs", "utf8");
    expect(gen).toMatch(/"structure",\s*"delivery",[^;]*"diagnosis"/);
    expect(gen).toMatch(/diagnosis:\s*join\(GENPROTO,\s*"runtime",\s*"v1",\s*"diagnosis\.swagger\.json"\)/);
  });
});
